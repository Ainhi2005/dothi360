import { Router } from 'express';
import { authenticate } from '../../common/middlewares/authenticate.middleware';
import { authorizeRole } from '../../common/middlewares/authorize.middleware';
import { ROLES } from '../../common/constants/roles';
import { exportCsv, exportXlsx, hotspots, notifications, sla, summary, trends, workload, aiMetrics, aiConfusion, aiComparison, aiSamplesCsv } from './admin-dashboard.controller';
const router = Router();
router.use(authenticate, authorizeRole(ROLES.ADMIN));
router.get('/dashboard/summary', summary);
router.get('/dashboard/trends', trends);
router.get('/dashboard/workload', workload);
router.get('/dashboard/sla', sla);
router.get('/dashboard/hotspots', hotspots);
router.get('/reports/incidents.csv', exportCsv);
router.get('/reports/incidents.xlsx', exportXlsx);
router.get('/notifications', notifications);
router.get('/ai/metrics', aiMetrics);
router.get('/ai/confusion', aiConfusion);
router.get('/ai/comparison', aiComparison);
router.get('/ai/evaluation-samples.csv', aiSamplesCsv);
export default router;
